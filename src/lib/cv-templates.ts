export const CV_TEMPLATE_MAP: Record<string, ICvTemplateDefinition> =
  Object.fromEntries(CV_TEMPLATES.map((tpl) => [tpl.id, tpl]));

export function getCvTemplate(templateId?: string | null): ICvTemplateDefinition {
  if (templateId && CV_TEMPLATE_MAP[templateId]) {
    return CV_TEMPLATE_MAP[templateId];
  }
  return CV_TEMPLATE_MAP[DEFAULT_CV_TEMPLATE_ID] ?? CV_TEMPLATES[0];
}

